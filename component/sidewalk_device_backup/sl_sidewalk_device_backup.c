void sl_sidewalk_device_backup_handle_backup_restore(void)
{
  sid_pal_mfg_store_region_t mfg_store_region = { 0 };
  sid_pal_mfg_store_init(mfg_store_region);

  if (is_backup_needed() && is_backup_possible()) {
    perform_backup();
  }
  if (is_restore_needed() && is_restore_possible()) {
    perform_restore();
  }

  backup_refresh();

  SL_SID_LOG_PAL_INFO("pal backup: %s ok", __func__);
}

